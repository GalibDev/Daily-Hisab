export function normalizeLanguage(value: string | null | undefined): AppLanguage {
  return value === "english" ? "english" : DEFAULT_LANGUAGE;
}

export function getStoredLanguage(): AppLanguage {
  if (typeof window === "undefined") return DEFAULT_LANGUAGE;
  return normalizeLanguage(window.localStorage.getItem(LANGUAGE_STORAGE_KEY));
}

export function translate(language: AppLanguage, key: TranslationKey, values?: Record<string, string | number>): string {
  let message: string = language === "bangla" ? bangla[key] : english[key];
  if (!values) return message;
  for (const [name, value] of Object.entries(values)) message = message.replaceAll(`{${name}}`, String(value));
  return message;
}
